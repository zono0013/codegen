func testProtos(t *testing.T) []*protogen.File {
	t.Helper()
	return prototest.Files(t, map[string]string{"a/v1/a.proto": `syntax = "proto3";
package a.v1;
message A {}
`})
}

// emit は固定のファイルを出力するだけのジェネレータ。
func emit(files map[string]string) func([]*protogen.File) (map[string][]byte, error) {
	return func([]*protogen.File) (map[string][]byte, error) {
		out := map[string][]byte{}
		for name, content := range files {
			out[name] = []byte(content)
		}
		return out, nil
	}
}

func TestRender(t *testing.T) {
	t.Run("Go ファイルはヘッダーを付けて gofmt する", func(t *testing.T) {
		got, err := Render(testProtos(t), Target{Comment: "//", Generator: "x/gen", Generate: emit(map[string]string{
			"x.gen.go": "\npackage x\nfunc  F( ) {  }\n",
		})})
		if err != nil {
			t.Fatal(err)
		}
		want := "// Code generated by make proto-gen (x/gen). DO NOT EDIT.\n\npackage x\n\nfunc F() {}\n"
		if string(got["x.gen.go"]) != want {
			t.Errorf("got %q, want %q", got["x.gen.go"], want)
		}
	})

	t.Run("Go 以外はヘッダーを付けるだけで整形しない", func(t *testing.T) {
		got, err := Render(testProtos(t), Target{Comment: "#", Generator: "x/gen", Generate: emit(map[string]string{"x.gen.yaml": "a:  1\n"})})
		if err != nil {
			t.Fatal(err)
		}
		if want := "# Code generated by make proto-gen (x/gen). DO NOT EDIT.\na:  1\n"; string(got["x.gen.yaml"]) != want {
			t.Errorf("got %q, want %q", got["x.gen.yaml"], want)
		}
	})

	t.Run("ジェネレータのエラーを返す", func(t *testing.T) {
		boom := errors.New("boom")
		_, err := Render(testProtos(t), Target{Name: "x", Generate: func([]*protogen.File) (map[string][]byte, error) { return nil, boom }})
		if !errors.Is(err, boom) {
			t.Errorf("err = %v, want boom", err)
		}
	})
}

func TestWrite(t *testing.T) {
	root := t.TempDir()
	put := func(rel, content string) {
		t.Helper()
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	ours := "// " + Marker + " (test). DO NOT EDIT.\n"
	put("out/stale.gen.txt", ours)                             // もう生成されない → 消す
	put("out/sub/stale.gen.txt", ours)                         // ネストしていても消す
	put("out/keep.gen.txt", ours)                              // 生成される → 上書き
	put("out/hand.txt", "hand written")                        // suffix が違う手書き → 残す
	put("out/foreign.gen.txt", "// Code generated by sqlc.\n") // 別ツールの生成物 → 残す
	put("out/handwritten.gen.txt", "hand written")             // 名前だけ .gen の手書き → 残す
	put("out/node_modules/x.gen.txt", ours)                    // node_modules は触らない
	put("out/vendor/x.gen.txt", ours)                          // vendor は触らない
	put("out/.cache/x.gen.txt", ours)                          // 隠しディレクトリは触らない

	target := Target{Out: "out", Suffix: ".gen.txt"}
	res, err := Write(root, target, map[string][]byte{
		"keep.gen.txt":    []byte("new"),
		"sub/new.gen.txt": []byte("created"),
	})
	if err != nil {
		t.Fatal(err)
	}

	read := func(rel string) (string, bool) {
		b, err := os.ReadFile(filepath.Join(root, rel))
		return string(b), err == nil
	}
	for rel, want := range map[string]string{
		"out/keep.gen.txt":           "new",
		"out/sub/new.gen.txt":        "created",
		"out/hand.txt":               "hand written",
		"out/foreign.gen.txt":        "// Code generated by sqlc.\n",
		"out/handwritten.gen.txt":    "hand written",
		"out/node_modules/x.gen.txt": ours,
		"out/vendor/x.gen.txt":       ours,
		"out/.cache/x.gen.txt":       ours,
	} {
		if got, ok := read(rel); !ok || got != want {
			t.Errorf("%s = %q (exists=%v), want %q", rel, got, ok, want)
		}
	}
	for _, rel := range []string{"out/stale.gen.txt", "out/sub/stale.gen.txt"} {
		if _, ok := read(rel); ok {
			t.Errorf("%s が消えていない", rel)
		}
	}
	slices.Sort(res.Deleted)
	if want := []string{"stale.gen.txt", "sub/stale.gen.txt"}; !slices.Equal(res.Deleted, want) {
		t.Errorf("Deleted = %v, want %v", res.Deleted, want)
	}
}

func TestPlan_DoesNotTouchFiles(t *testing.T) {
	root := t.TempDir()
	stale := filepath.Join(root, "out", "stale.gen.txt")
	if err := os.MkdirAll(filepath.Dir(stale), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(stale, []byte("// "+Marker+". DO NOT EDIT.\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	target := Target{Out: "out", Suffix: ".gen.txt"}

	res, err := Plan(root, target, map[string][]byte{"a.gen.txt": []byte("new")})
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(res.Written, []string{"a.gen.txt"}) || !slices.Equal(res.Deleted, []string{"stale.gen.txt"}) {
		t.Errorf("Plan = %+v", res)
	}
	if _, err := os.Stat(filepath.Join(root, "out", "a.gen.txt")); err == nil {
		t.Errorf("Plan がファイルを書いた")
	}
	if _, err := os.Stat(stale); err != nil {
		t.Errorf("Plan がファイルを消した")
	}
}

func TestWrite_UnchangedFileIsNotRewritten(t *testing.T) {
	root := t.TempDir()
	target := Target{Out: "out", Suffix: ".gen.txt"}
	files := map[string][]byte{"a.gen.txt": []byte("same")}
	if _, err := Write(root, target, files); err != nil {
		t.Fatal(err)
	}
	res, err := Write(root, target, files)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Written) != 0 {
		t.Errorf("内容が同じなのに書き直した: %v", res.Written)
	}
}

func TestTargets(t *testing.T) {
	cfg := config.Config{Proto: "proto", Targets: config.Targets{
		Server:  config.Server{Out: "backend", ImportPath: "example.com/x/backend"},
		Front:   config.Front{Out: "web/gen", Client: "@/api"},
		OpenAPI: config.OpenAPI{Out: "api", Title: "T", Version: "1"},
	}}
	targets := Targets(cfg)
	var got []string
	for _, tg := range targets {
		got = append(got, tg.Name+"="+tg.Out)
	}
	if want := []string{"server=backend", "front=web/gen", "openapi=api"}; !slices.Equal(got, want) {
		t.Errorf("targets = %v, want %v", got, want)
	}
	for i, a := range targets {
		if !strings.HasPrefix(a.Suffix, ".gen.") || a.Comment == "" || a.Generator == "" || a.Generate == nil {
			t.Errorf("target %d が不完全: %+v", i, a)
		}
	}
}

func TestPlan_SkipsNestedRepositories(t *testing.T) {
	root := t.TempDir()
	target := Target{Out: "out", Suffix: ".gen.txt"}
	nested := filepath.Join(root, "out", "vendored")
	if err := os.MkdirAll(nested, 0o755); err != nil {
		t.Fatal(err)
	}
	// Submodule のチェックアウトは .git をファイルとして持つ
	if err := os.WriteFile(filepath.Join(nested, ".git"), []byte("gitdir: ../../.git/modules/vendored\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	theirs := filepath.Join(nested, "x.gen.txt")
	if err := os.WriteFile(theirs, []byte("// "+Marker+" (other). DO NOT EDIT.\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	res, err := Plan(root, target, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Deleted) != 0 {
		t.Errorf("別リポジトリの中の生成物を消そうとした: %v", res.Deleted)
	}
}
