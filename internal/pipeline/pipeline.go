// Package pipeline はジェネレータを実行し、生成物をリポジトリへ書き出す。
// 何を生成するか（Targets）はこのパッケージだけが知っている。どこへ生成するかは codegen.yaml（internal/config）で受け取る。
package pipeline

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"

	"github.com/zono0013/codegen/internal/config"
	"github.com/zono0013/codegen/internal/gogen"
	"github.com/zono0013/codegen/internal/openapigen"
	"github.com/zono0013/codegen/internal/tsgen"
)

type Target struct {
	Name      string
	Out       string // 生成先のプロジェクトのルートからの相対ディレクトリ（スラッシュ区切り）
	Suffix    string
	Comment   string                                            // 生成物の行コメント記号（ヘッダー行に使う）
	Generator string                                            // ヘッダーに出す生成元
	Generate  func([]*protogen.File) (map[string][]byte, error) // Out からの相対パス → 内容
}

// Targets は cfg の出力先に対する生成設定。
func Targets(cfg config.Config) []Target {
	t := cfg.Targets
	return []Target{
		{Name: "server", Out: t.Server.Out, Suffix: ".gen.go", Comment: "//", Generator: "codegen/internal/gogen", Generate: gogen.New(gogen.Params{ImportPath: t.Server.ImportPath})},
		{Name: "front", Out: t.Front.Out, Suffix: ".gen.ts", Comment: "//", Generator: "codegen/internal/tsgen", Generate: tsgen.New(tsgen.Params{Client: t.Front.Client})},
		{Name: "openapi", Out: t.OpenAPI.Out, Suffix: ".gen.yaml", Comment: "#", Generator: "codegen/internal/openapigen", Generate: openapigen.New(openapigen.Params{
			Title:   t.OpenAPI.Title,
			Version: t.OpenAPI.Version,
		})},
	}
}

// Render は t を実行し、「Out からの相対パス → 内容」を返す。全ファイルの先頭にヘッダー行を付け、Go は gofmt する。
func Render(protos []*protogen.File, t Target) (map[string][]byte, error) {
	files, err := t.Generate(protos)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", t.Name, err)
	}
	header := t.Comment + " " + Marker + " (" + t.Generator + "). DO NOT EDIT.\n"
	for name, content := range files {
		content = append([]byte(header), content...)
		if strings.HasSuffix(name, ".go") {
			if content, err = format.Source(content); err != nil {
				return nil, fmt.Errorf("%s: gofmt %s: %w", t.Name, name, err)
			}
		}
		files[name] = content
	}
	return files, nil
}

// RenderAll は全 Target を Render し、「Target 名 → Out からの相対パス → 内容」を返す。
func RenderAll(protos []*protogen.File, targets []Target) (map[string]map[string][]byte, error) {
	out := make(map[string]map[string][]byte, len(targets))
	for _, t := range targets {
		files, err := Render(protos, t)
		if err != nil {
			return nil, err
		}
		out[t.Name] = files
	}
	return out, nil
}

// Marker は Render が全生成物の 1 行目に入れる。古い生成物として削除するのはこれを持つファイルだけ
// （同じ suffix を使う別ツールの生成物や手書きファイルを消さないため）。
const Marker = "Code generated by make proto-gen"

// Result は Write（Plan）が変更する（した）ファイル。Out からの相対パス。
type Result struct {
	Written []string // 新規 or 内容が変わる
	Deleted []string // 生成されなくなった古い生成物
}

// Plan は Write が何をするかをファイルに触れずに返す。
// 内容が変わらないファイルは Written に含めない（無駄な mtime 更新でビルドキャッシュを壊さないため）。
func Plan(root string, t Target, files map[string][]byte) (Result, error) {
	var res Result
	dir := filepath.Join(root, filepath.FromSlash(t.Out))

	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		cur, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
		if err == nil && bytes.Equal(cur, files[name]) {
			continue
		}
		res.Written = append(res.Written, name)
	}

	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if p != dir && (d.Name() == "node_modules" || d.Name() == "vendor" || strings.HasPrefix(d.Name(), ".") || isRepository(p)) {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(p, t.Suffix) {
			return nil
		}
		rel, err := filepath.Rel(dir, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if _, generated := files[rel]; generated {
			return nil
		}
		ours, err := hasMarker(p)
		if err != nil {
			return err
		}
		if ours {
			res.Deleted = append(res.Deleted, rel)
		}
		return nil
	})
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return res, err
	}
	return res, nil
}

// Write は Plan のとおりに files を root/t.Out 配下へ書き出し、古い生成物を削除する。
func Write(root string, t Target, files map[string][]byte) (Result, error) {
	res, err := Plan(root, t, files)
	if err != nil {
		return res, err
	}
	dir := filepath.Join(root, filepath.FromSlash(t.Out))
	for _, name := range res.Written {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return res, err
		}
		if err := os.WriteFile(p, files[name], 0o644); err != nil {
			return res, err
		}
	}
	for _, name := range res.Deleted {
		if err := os.Remove(filepath.Join(dir, filepath.FromSlash(name))); err != nil {
			return res, err
		}
	}
	return res, nil
}

// isRepository は dir が別の Git リポジトリ（Submodule を含む）のチェックアウトかを返す。その中の生成物は他人のもの。
func isRepository(dir string) bool {
	_, err := os.Lstat(filepath.Join(dir, ".git"))
	return err == nil
}

func hasMarker(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	head := make([]byte, 256)
	n, err := io.ReadFull(f, head)
	if err != nil && !errors.Is(err, io.ErrUnexpectedEOF) && !errors.Is(err, io.EOF) {
		return false, err
	}
	firstLine, _, _ := bytes.Cut(head[:n], []byte("\n"))
	return bytes.Contains(firstLine, []byte(Marker)), nil
}
