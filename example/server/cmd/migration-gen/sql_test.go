func usersTable() *tableSchema {
	return &tableSchema{
		Name: "users",
		Columns: map[string]columnSchema{
			"id":    {Name: "id", SQLType: "text", PrimaryKey: true, NotNull: true},
			"email": {Name: "email", SQLType: "text", NotNull: true, Unique: true},
		},
	}
}

func TestEmitCreate_NamesUniqueConstraint(t *testing.T) {
	sql := emitSQL(tableChange{Table: "users", Kind: changeCreate, NewTable: usersTable()})
	// 後から外すときと同じ名前にするため、Postgres 既定の名前（users_email_key）に任せない
	if want := `"email" text NOT NULL CONSTRAINT "uq_users_email" UNIQUE`; !strings.Contains(sql, want) {
		t.Errorf("%q が無い:\n%s", want, sql)
	}
}

func TestEmitAlter_DropUniqueFindsConstraintByColumn(t *testing.T) {
	sql := emitSQL(tableChange{Table: "users", Kind: changeAlter, DropUniqueCols: []string{"email"}})
	// 名前ではなく列で探す（名前を明示する前の既定の名前、手で付けた名前、長い名前の切り詰めでも外せるように）。
	// 見つからなければ失敗させ、snapshot と DB が食い違ったまま進まないようにする
	for _, want := range []string{"pg_constraint", "contype = 'u'", "attname = 'email'", "RAISE EXCEPTION"} {
		if !strings.Contains(sql, want) {
			t.Errorf("%q が無い:\n%s", want, sql)
		}
	}
}

type intPKTag struct {
	ID   int64  `gorm:"column:id;primaryKey"`
	Name string `gorm:"column:name;not null"`
}

type stringPKTag struct {
	ID string `gorm:"column:id;primaryKey"`
}

func TestBuildSchemas_IntegerPKIsIdentity(t *testing.T) {
	// GORM は整数の primaryKey を自動採番として扱い、INSERT で 0 を送らない。DB 側で採番させる
	tables, err := buildSchemas([]any{&intPKTag{}, &stringPKTag{}})
	if err != nil {
		t.Fatal(err)
	}
	if c := tables["int_pk_tags"].Columns["id"]; !c.Identity {
		t.Errorf("整数の主キーが Identity になっていない: %+v", c)
	}
	if c := tables["int_pk_tags"].Columns["name"]; c.Identity {
		t.Errorf("主キーでない列が Identity になっている: %+v", c)
	}
	if c := tables["string_pk_tags"].Columns["id"]; c.Identity {
		t.Errorf("文字列の主キーが Identity になっている: %+v", c)
	}
}

func TestEmitCreate_IdentityColumn(t *testing.T) {
	sql := emitSQL(tableChange{Table: "tags", Kind: changeCreate, NewTable: &tableSchema{
		Name:    "tags",
		Columns: map[string]columnSchema{"id": {Name: "id", SQLType: "bigint", PrimaryKey: true, NotNull: true, Identity: true}},
	}})
	if want := `"id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`; !strings.Contains(sql, want) {
		t.Errorf("%q が無い:\n%s", want, sql)
	}
}

func TestEmitAlter_Identity(t *testing.T) {
	from := columnSchema{Name: "id", SQLType: "bigint", PrimaryKey: true, NotNull: true}
	to := from
	to.Identity = true
	if columnEqual(from, to) {
		t.Fatal("Identity の違いを差分として扱っていない")
	}
	add := emitSQL(tableChange{Table: "tags", Kind: changeAlter, AlterColumns: []columnAlter{{Name: "id", From: from, To: to}}})
	if want := `ALTER TABLE "tags" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY;`; !strings.Contains(add, want) {
		t.Errorf("%q が無い:\n%s", want, add)
	}
	drop := emitSQL(tableChange{Table: "tags", Kind: changeAlter, AlterColumns: []columnAlter{{Name: "id", From: to, To: from}}})
	if want := `ALTER TABLE "tags" ALTER COLUMN "id" DROP IDENTITY;`; !strings.Contains(drop, want) {
		t.Errorf("%q が無い:\n%s", want, drop)
	}
}

// connectTestSchema は MIGRATION_TEST_DATABASE_URL の Postgres につなぎ、テスト専用のスキーマを search_path にする。
// URL が無ければテストを飛ばす（CI では Postgres を立てて実行する）。
// 開発用の DB を指していても既存のテーブルを壊さないよう、スキーマはテストの終わりに消す。
func connectTestSchema(t *testing.T) (context.Context, *pgx.Conn) {
	t.Helper()
	url := os.Getenv("MIGRATION_TEST_DATABASE_URL")
	if url == "" {
		t.Skip("MIGRATION_TEST_DATABASE_URL が無い")
	}
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, url)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = conn.Close(ctx) })
	schema := fmt.Sprintf("migration_gen_test_%d", time.Now().UnixNano())
	mustExecSQL(t, conn, fmt.Sprintf(`CREATE SCHEMA %q`, schema))
	t.Cleanup(func() { _, _ = conn.Exec(ctx, fmt.Sprintf(`DROP SCHEMA %q CASCADE`, schema)) })
	mustExecSQL(t, conn, fmt.Sprintf(`SET search_path TO %q`, schema))
	return ctx, conn
}

func mustExecSQL(t *testing.T, conn *pgx.Conn, sql string) {
	t.Helper()
	if _, err := conn.Exec(context.Background(), sql); err != nil {
		t.Fatalf("%v\n%s", err, sql)
	}
}

// TestIdentityColumn_Postgres は、整数の主キーを生成した SQL で作ると、id を送らない INSERT で DB が採番することを確かめる。
// 後から IDENTITY を足す・外す ALTER も実際に通るかを見る。
func TestIdentityColumn_Postgres(t *testing.T) {
	ctx, conn := connectTestSchema(t)
	pk := columnSchema{Name: "id", SQLType: "bigint", PrimaryKey: true, NotNull: true}
	identity := pk
	identity.Identity = true
	insertID := func(t *testing.T) int64 {
		t.Helper()
		var id int64
		if err := conn.QueryRow(ctx, `INSERT INTO "tags" DEFAULT VALUES RETURNING "id"`).Scan(&id); err != nil {
			t.Fatal(err)
		}
		return id
	}

	mustExecSQL(t, conn, emitSQL(tableChange{Table: "tags", Kind: changeCreate, NewTable: &tableSchema{
		Name: "tags", Columns: map[string]columnSchema{"id": identity},
	}}))
	if a, b := insertID(t), insertID(t); a == 0 || b <= a {
		t.Fatalf("採番された id = %d, %d", a, b)
	}

	mustExecSQL(t, conn, emitSQL(tableChange{Table: "tags", Kind: changeAlter, AlterColumns: []columnAlter{{Name: "id", From: identity, To: pk}}}))
	if _, err := conn.Exec(ctx, `INSERT INTO "tags" DEFAULT VALUES`); err == nil {
		t.Fatal("IDENTITY を外した後も id 無しで INSERT できた")
	}
	mustExecSQL(t, conn, `DELETE FROM "tags"`)
	mustExecSQL(t, conn, emitSQL(tableChange{Table: "tags", Kind: changeAlter, AlterColumns: []columnAlter{{Name: "id", From: pk, To: identity}}}))
	if id := insertID(t); id == 0 {
		t.Fatal("IDENTITY を足した後に採番されない")
	}
}

// TestUniqueConstraintLifecycle_Postgres は、生成した SQL を実際の Postgres に適用して、unique を作る・外す・足すが
// 通ることを確かめる。
func TestUniqueConstraintLifecycle_Postgres(t *testing.T) {
	ctx, conn := connectTestSchema(t)
	exec := func(t *testing.T, sql string) error {
		t.Helper()
		_, err := conn.Exec(ctx, sql)
		return err
	}
	mustExec := func(t *testing.T, sql string) { t.Helper(); mustExecSQL(t, conn, sql) }

	// uniqueNames は users の unique 制約の名前を返す
	uniqueNames := func(t *testing.T) []string {
		t.Helper()
		rows, err := conn.Query(ctx, `SELECT conname FROM pg_constraint WHERE conrelid = 'users'::regclass AND contype = 'u' ORDER BY conname`)
		if err != nil {
			t.Fatal(err)
		}
		names, err := pgx.CollectRows(rows, pgx.RowTo[string])
		if err != nil {
			t.Fatal(err)
		}
		return names
	}
	expectUnique := func(t *testing.T, want ...string) {
		t.Helper()
		if got := uniqueNames(t); strings.Join(got, ",") != strings.Join(want, ",") {
			t.Fatalf("unique 制約 = %v, want %v", got, want)
		}
	}
	dropUnique := emitSQL(tableChange{Table: "users", Kind: changeAlter, DropUniqueCols: []string{"email"}})
	reset := func(t *testing.T) { mustExec(t, `DROP TABLE IF EXISTS "users"`) }

	t.Run("生成した SQL で作ったテーブル", func(t *testing.T) {
		reset(t)
		mustExec(t, emitSQL(tableChange{Table: "users", Kind: changeCreate, NewTable: usersTable()}))
		expectUnique(t, "uq_users_email")
		mustExec(t, dropUnique)
		expectUnique(t)
		mustExec(t, emitSQL(tableChange{Table: "users", Kind: changeAlter, AddUniqueCols: []string{"email"}}))
		expectUnique(t, "uq_users_email")
		mustExec(t, dropUnique)
		expectUnique(t)
	})

	t.Run("ADD COLUMN で足した unique の列", func(t *testing.T) {
		reset(t)
		mustExec(t, `CREATE TABLE "users" ("id" text PRIMARY KEY)`)
		mustExec(t, emitSQL(tableChange{Table: "users", Kind: changeAlter, AddColumns: []columnSchema{
			{Name: "email", SQLType: "text", Unique: true},
		}}))
		expectUnique(t, "uq_users_email")
		mustExec(t, dropUnique)
		expectUnique(t)
	})

	t.Run("名前を明示する前の CREATE TABLE で作ったテーブル", func(t *testing.T) {
		reset(t)
		mustExec(t, `CREATE TABLE "users" ("id" text PRIMARY KEY, "email" text NOT NULL UNIQUE)`)
		expectUnique(t, "users_email_key")
		mustExec(t, dropUnique)
		expectUnique(t)
	})

	t.Run("手で別の名前を付けた制約", func(t *testing.T) {
		reset(t)
		mustExec(t, `CREATE TABLE "users" ("id" text PRIMARY KEY, "email" text NOT NULL CONSTRAINT "my_email_unique" UNIQUE)`)
		mustExec(t, dropUnique)
		expectUnique(t)
	})

	t.Run("同じ列に unique が 2 つあれば両方外す", func(t *testing.T) {
		reset(t)
		mustExec(t, `CREATE TABLE "users" ("id" text PRIMARY KEY, "email" text NOT NULL UNIQUE)`)
		mustExec(t, `ALTER TABLE "users" ADD CONSTRAINT "uq_users_email" UNIQUE ("email")`)
		expectUnique(t, "uq_users_email", "users_email_key")
		mustExec(t, dropUnique)
		expectUnique(t)
	})

	t.Run("外す制約が無ければ失敗する", func(t *testing.T) {
		reset(t)
		mustExec(t, `CREATE TABLE "users" ("id" text PRIMARY KEY, "email" text NOT NULL)`)
		err := exec(t, dropUnique)
		if err == nil || !strings.Contains(err.Error(), "unique constraint on") || !strings.Contains(err.Error(), "not found") {
			t.Fatalf("err = %v, want 制約が見つからないエラー（snapshot と DB の食い違いに気づけるように）", err)
		}
	})
}
